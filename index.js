function fibo(num) {
    let initial = 0
    const arr = [0, 1]
    while(initial < num){
        let lenght1 = arr.length - 1
        let lenght2 = arr.length - 2
        arr.push(arr[lenght1] + arr[lenght2])
        initial ++
    }

    return arr
}

console.log(fibo(7))